#!/usr/bin/env python3
"""Every word setup says, on one page: docs/setup-script.md, generated from System/Start.md, System/Setup Procedure.md
and System/Adding Your Computer.md. Edit the source files, then run this; `--check` fails when the page is stale."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCES = ["Start.md", "Setup Procedure.md", "Adding Your Computer.md"]
OUT = ROOT / "docs" / "setup-script.md"
QUOTE = re.compile(r'"([^"\n]*)"')
CODE = re.compile(r"`([^`\n]*)`")
ASK = re.compile(r'"([^"\n]+\?)"[^\n]*?Options:\s*([^\n]+)')


def extract(text, source):
    items, section = [], ""
    for line in text.replace("\r\n", "\n").split("\n"):
        if line.startswith("## "):
            section = line[3:].strip()
            continue
        line = CODE.sub(lambda c: c.group(1).replace('"', ""), line)
        m = ASK.search(line)
        if m:
            items.append((section, "ask", f"{m.group(1)} Options: {m.group(2).strip()}"))
            continue
        for q in QUOTE.findall(line):
            if len(q) >= 20 and len(q.split()) >= 6:
                items.append((section, "say", q))
    return items


def render(by_source):
    out = ["# Everything setup says\n", "Generated by `scripts/setup/script-doc.py` from the files below. Edit those files, not this page.\n"]
    for source, items in by_source.items():
        out.append(f"\n## {source}\n")
        last = None
        for section, kind, text in items:
            if section != last:
                out.append(f"\n### {section}\n")
                last = section
            out.append(f"- {'ASK' if kind == 'ask' else 'SAY'}: {text}\n")
    return "".join(out)


def main(argv):
    by_source = {}
    for name in SOURCES:
        by_source[name] = extract((ROOT / "System" / name).read_text(encoding="utf-8"), name)
    text = render(by_source)
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text:
            print("STALE docs/setup-script.md: run python3 scripts/setup/script-doc.py")
            return 1
        print("CURRENT")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"WROTE {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
